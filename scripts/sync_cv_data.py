#!/usr/bin/env python3
"""Generate the website's CV data from the sibling CV repository."""

import argparse
from pathlib import Path

import yaml

from cv_data import ROOT, load_yaml, localize, normalize_publications


def sync_data(data_dir, output_dir, urls_path):
    # Read and convert everything before changing the committed snapshots.
    cv = load_yaml(data_dir / 'cv.yml')
    labels = load_yaml(data_dir / 'i18n.yml')
    if 'sections' not in cv or 'education' not in labels:
        raise ValueError(f'Invalid CV data in {data_dir}')
    for lang in ('en', 'zh'):
        localize(cv, lang)
        localize(labels, lang)
    pubs = normalize_publications(load_yaml(data_dir / 'publications.yml'),
                                  load_yaml(urls_path))
    outputs = {
        'cv.yml': (data_dir / 'cv.yml').read_text(encoding='utf-8'),
        'i18n.yml': (data_dir / 'i18n.yml').read_text(encoding='utf-8'),
        'publications.yml': yaml.safe_dump(pubs, allow_unicode=True, sort_keys=False),
    }
    output_dir.mkdir(parents=True, exist_ok=True)
    for name, content in outputs.items():
        text = '# Generated by scripts/sync_cv_data.py from CV/data; do not edit.\n' + content
        path = output_dir / name
        if not path.exists() or path.read_text(encoding='utf-8') != text:
            path.write_text(text, encoding='utf-8')
        print(f'Synced {path}')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data-dir', type=Path, default=ROOT.parent / 'CV' / 'data')
    parser.add_argument('--output-dir', type=Path, default=ROOT / '_data')
    parser.add_argument('--urls', type=Path, default=ROOT / '_data/publication_urls.yml')
    args = parser.parse_args()
    try:
        sync_data(args.data_dir, args.output_dir, args.urls)
    except (OSError, ValueError, KeyError, yaml.YAMLError) as error:
        parser.exit(1, f'CV data sync failed: {error}\n')


if __name__ == '__main__':
    main()
